def calculate_checksum(data: bytes) -> int:
    """
    Calculate the one's complement checksum for Aula Hero 68HE packets.
    
    Args:
        data: First 63 bytes of the 64-byte HID report
    
    Returns:
        Checksum byte (0-255)
    """
    return (0xFF - (sum(data) & 0xFF)) & 0xFF

def verify_packet(packet: bytes) -> bool:
    """
    Verify a complete 64-byte packet has a valid checksum.
    
    Args:
        packet: Full 64-byte HID report
    
    Returns:
        True if checksum is valid, False otherwise
    """
    if len(packet) != 64:
        return False
    return calculate_checksum(packet[:-1]) == packet[-1]

