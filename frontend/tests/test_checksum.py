from src.checksum import calculate_checksum, verify_packet

def test_spacebar_packet_checksum():
    """    
    Checksum should be able to return the final byte accurately when given the first 63 bytes of the packet
    
    Example usage for Spacebar to Spacebar packet    
    """
     
    
    packet = bytes([
        0x09, 0x03, 0x00, 0x00, 0x01, 0x00, 0x06, 0x00,
        0x46, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00  # Checksum
    ])
    
    complete_packet = bytes([ # This packet must have all 64 bytes in order to be checked for validity
        0x09, 0x03, 0x00, 0x00, 0x01, 0x00, 0x06, 0x00,
        0x46, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x7a  # Checksum
    ])
    
    # Calculate the checksum
    result = calculate_checksum(packet)
   
    assert result == 0x7a
    assert verify_packet(complete_packet) is True
